-- Rádio Máxima FM — estrutura do banco (MySQL 5.7+ / MariaDB 10.3+)
-- Importar no phpMyAdmin (Hostinger) ou: mysql -u USUARIO -p BANCO < schema.sql
-- Depois importe seed.sql (conteúdo de exemplo) e crie o primeiro usuário (ver LEIAME.md).

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS usuarios (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  senha_hash VARCHAR(255) NOT NULL,
  sessao_versao INT UNSIGNED NOT NULL DEFAULT 1,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS login_tentativas (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ip VARCHAR(45) NOT NULL,
  momento DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (ip, momento)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS config (
  chave VARCHAR(60) PRIMARY KEY,
  valor MEDIUMTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS banners (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  titulo VARCHAR(160) NOT NULL DEFAULT '',
  subtitulo VARCHAR(255) NOT NULL DEFAULT '',
  imagem VARCHAR(255) NULL,
  link VARCHAR(255) NOT NULL DEFAULT '',
  botao VARCHAR(60) NOT NULL DEFAULT '',
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  ordem INT NOT NULL DEFAULT 0,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS programas (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  apresentador VARCHAR(160) NOT NULL DEFAULT '',
  descricao TEXT NULL,
  foto VARCHAR(255) NULL,
  cor CHAR(7) NOT NULL DEFAULT '#e3161b',
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Grade semanal. dia: 0 = domingo ... 6 = sábado.
-- inicio/fim em minutos desde 00:00 (fim = 1440 significa 24:00).
CREATE TABLE IF NOT EXISTS grade (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  programa_id INT UNSIGNED NOT NULL,
  dia TINYINT UNSIGNED NOT NULL,
  inicio SMALLINT UNSIGNED NOT NULL,
  fim SMALLINT UNSIGNED NOT NULL,
  INDEX (dia, inicio),
  CONSTRAINT fk_grade_programa FOREIGN KEY (programa_id) REFERENCES programas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS noticias (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  titulo VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL UNIQUE,
  resumo VARCHAR(400) NOT NULL DEFAULT '',
  conteudo MEDIUMTEXT NOT NULL,
  imagem VARCHAR(255) NULL,
  categoria VARCHAR(60) NOT NULL DEFAULT 'Geral',
  destaque TINYINT(1) NOT NULL DEFAULT 0,
  publicado TINYINT(1) NOT NULL DEFAULT 1,
  publicado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  visualizacoes INT UNSIGNED NOT NULL DEFAULT 0,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX (publicado, publicado_em)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS eventos (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  titulo VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL UNIQUE,
  descricao TEXT NULL,
  local VARCHAR(200) NOT NULL DEFAULT '',
  data_evento DATE NOT NULL,
  capa_id INT UNSIGNED NULL,
  publicado TINYINT(1) NOT NULL DEFAULT 1,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (publicado, data_evento)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS evento_fotos (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  evento_id INT UNSIGNED NOT NULL,
  arquivo VARCHAR(255) NOT NULL,
  legenda VARCHAR(255) NOT NULL DEFAULT '',
  ordem INT NOT NULL DEFAULT 0,
  INDEX (evento_id, ordem),
  CONSTRAINT fk_foto_evento FOREIGN KEY (evento_id) REFERENCES eventos(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS patrocinadores (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(160) NOT NULL,
  logo VARCHAR(255) NULL,
  link VARCHAR(255) NOT NULL DEFAULT '',
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  ordem INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mensagens (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL DEFAULT '',
  telefone VARCHAR(40) NOT NULL DEFAULT '',
  cidade VARCHAR(120) NOT NULL DEFAULT '',
  assunto VARCHAR(60) NOT NULL DEFAULT 'Contato',
  mensagem TEXT NOT NULL,
  lida TINYINT(1) NOT NULL DEFAULT 0,
  ip VARCHAR(45) NOT NULL DEFAULT '',
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (lida, criado_em)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
